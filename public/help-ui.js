export function helpMarkup() {
  const start = START.map(
    ([title, text, page], i) =>
      `<li class="help-step"><span class="help-step-number">${i + 1}</span><span><b>${esc(title)}</b><small>${esc(text)}</small></span>${
        page
          ? `<button type="button" data-page="${esc(page)}" data-action="navigatePage" data-action-event="click" aria-label="Открыть ${esc(page)}">${icon("chevron")}</button>`
          : `<button type="button" data-action="openAddChooser" data-action-event="click" aria-label="Добавить операцию">${icon("plus")}</button>`
      }</li>`,
  ).join("");
  const sections = SECTIONS.map(
    ([name, text]) => `<div class="help-term"><dt>${esc(name)}</dt><dd>${esc(text)}</dd></div>`,
  ).join("");
  const faq = FAQ.map(
    ([group, items]) =>
      `<section class="help-group"><h2>${esc(group)}</h2>${items
        .map(
          ([q, a]) =>
            `<details class="help-item"><summary>${esc(q)}${icon("chevron")}</summary><p>${esc(a)}</p></details>`,
        )
        .join("")}</section>`,
  ).join("");
  return `<div class="help-layout"><section class="help-start"><h2>Быстрый старт</h2><ol>${start}</ol></section><section class="help-sections"><h2>Что есть что</h2><dl>${sections}</dl></section>${faq}<p class="muted help-contact">Не нашли ответ? Напишите на <b>info@multiknopka.ru</b>. <a href="/privacy">Политика конфиденциальности</a></p></div>`;
}
